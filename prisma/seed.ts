/**
 * Runs on every container start (see docker-entrypoint.sh), so it must be SAFE TO RE-RUN:
 *  - it only inserts records that are missing,
 *  - it never deletes or overwrites data people changed in the app
 *    (customers, payment status, product prices / images, new products).
 *
 * The one exception is a one-time catalog migration: the first time it sees a database
 * whose products have no sortOrder yet (the old, messy import), it replaces that catalog
 * with the clean one extracted from the Word price list (data/catalog.json).
 */
import { PrismaClient, CustomerTier, CustomerStatus, PaymentStatus } from "@prisma/client";
import fs from "fs";
import path from "path";

const prisma = new PrismaClient();

function readJson(file: string): any {
  const full = path.join(process.cwd(), "data", file);
  if (!fs.existsSync(full)) return null;
  try {
    return JSON.parse(fs.readFileSync(full, "utf-8").replace(/^﻿/, ""));
  } catch (err) {
    console.warn(`Could not read ${file}:`, err);
    return null;
  }
}

type CatalogProduct = { sku: string; name: string; category: string; wholesalePrice: number; imageUrl: string | null; sortOrder: number };

async function migrateCatalog(catalog: CatalogProduct[]) {
  const alreadyMigrated = (await prisma.product.count({ where: { sortOrder: { gt: 0 } } })) > 0;

  if (alreadyMigrated) {
    // Normal start: only add catalog items that are missing; never touch edited ones.
    const existing = new Set((await prisma.product.findMany({ select: { sku: true } })).map((p) => p.sku));
    const missing = catalog.filter((p) => !existing.has(p.sku));
    if (missing.length > 0) {
      await prisma.product.createMany({ data: missing.map(toProductData), skipDuplicates: true });
    }
    console.log(`>> Catalog up to date (${missing.length} missing products added).`);
    return;
  }

  console.log(">> One-time catalog migration: loading clean catalog from the Word price list...");
  const old = await prisma.product.findMany({
    select: { id: true, sku: true, _count: { select: { quoteItems: true } } },
  });

  // Free up the SKUs first. Old products used in saved quotes are kept (renamed, category "Other")
  // so those quotes stay intact; the rest get a temporary SKU and are removed below.
  for (const p of old) {
    const used = p._count.quoteItems > 0;
    await prisma.product.update({
      where: { id: p.id },
      data: used
        ? { sku: `OLD-${p.sku}-${p.id.slice(0, 4)}`, category: "Other", sortOrder: 100000 }
        : { sku: `TMP-${p.id}` },
    });
  }

  await prisma.product.createMany({ data: catalog.map(toProductData), skipDuplicates: true });

  // Seeded demo order lines pointed at old products: move them to the first catalog product.
  const first = await prisma.product.findFirst({ where: { sku: catalog[0].sku } });
  const oldIds = old.filter((p) => p._count.quoteItems === 0).map((p) => p.id);
  if (first && oldIds.length > 0) {
    await prisma.orderItem.updateMany({ where: { productId: { in: oldIds } }, data: { productId: first.id } });
    await prisma.stockMovement.deleteMany({ where: { productId: { in: oldIds } } });
    const removed = await prisma.product.deleteMany({ where: { id: { in: oldIds } } });
    console.log(`>> Replaced ${removed.count} old products with ${catalog.length} catalog products.`);
  }
}

function toProductData(p: CatalogProduct) {
  return {
    sku: p.sku,
    name: p.name,
    category: p.category,
    imageUrl: p.imageUrl,
    wholesalePrice: Number(p.wholesalePrice) || 0,
    sortOrder: p.sortOrder,
  };
}

// Notes generated by the original spreadsheet import (they contain profit figures); not written by people.
const AUTO_NOTE_PREFIX = "Khach hang B2B thuc te tu sheet";

async function seedCustomers(customers: any[]) {
  const firstProduct = await prisma.product.findFirst({ orderBy: { sortOrder: "asc" } });
  let added = 0;

  const cleared = await prisma.customer.updateMany({ where: { notes: { startsWith: AUTO_NOTE_PREFIX } }, data: { notes: null } });
  if (cleared.count > 0) console.log(`>> Cleared ${cleared.count} auto-generated import notes.`);

  for (const c of customers) {
    const exists = await prisma.customer.findUnique({ where: { id: c.id }, select: { id: true } });
    if (!exists) {
      await prisma.customer.create({
        data: {
          id: c.id,
          businessName: c.businessName,
          contactPerson: c.contactPerson,
          phone: c.phone,
          email: c.email,
          address: c.address,
          city: c.city,
          state: c.state,
          zipCode: c.zipCode,
          birthday: c.birthday ? new Date(c.birthday) : null,
          assignedSale: c.assignedSale || "admin",
          tier: (c.tier as CustomerTier) || CustomerTier.STANDARD,
          status: (c.status as CustomerStatus) || CustomerStatus.ACTIVE,
          notes: c.notes && !String(c.notes).startsWith(AUTO_NOTE_PREFIX) ? c.notes : null,
        },
      });
      added++;
    }

    // Orders: create the missing ones only, so payment status marked in the app is kept.
    if (!firstProduct) continue;
    for (const ord of c.orders || []) {
      const has = await prisma.order.findUnique({ where: { orderNumber: ord.orderNumber }, select: { id: true } });
      if (has) continue;
      await prisma.order.create({
        data: {
          orderNumber: ord.orderNumber,
          customerId: c.id,
          totalAmount: ord.totalAmount,
          paidAmount: ord.paidAmount,
          paymentStatus: ord.paymentStatus as PaymentStatus,
          dueDate: new Date(ord.dueDate || ord.createdAt || Date.now()),
          createdAt: ord.createdAt ? new Date(ord.createdAt) : undefined,
          saleRep: ord.saleRep,
          notes: ord.notes,
          items: {
            create: [{ productId: firstProduct.id, quantity: 1, unitPrice: firstProduct.wholesalePrice }],
          },
        },
      });
    }
  }
  console.log(`>> Customers checked (${added} new from sheet).`);
}

async function main() {
  console.log(">> Seeding JKIOCEAN database (insert-only)...");

  const catalog = readJson("catalog.json");
  if (catalog?.products?.length) await migrateCatalog(catalog.products);

  const customers = readJson("customers_extracted.json");
  if (Array.isArray(customers)) await seedCustomers(customers);

  console.log(">> Seeding done.");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
